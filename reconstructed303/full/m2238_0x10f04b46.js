function R(s) {
  switch (s) {
    case "userSettings":
    case "projectSettings":
    case "localSettings":
      return "persistent";
    case "cliArg":
    case "session":
      return "session";
    default:
      return "readonly"
  }
}

function p(s, r) {
  let a = Yzt(s.ruleValue),
    l = r?.raw ?? Sn(s.ruleValue),
    o = r?.notInEffect ? "readonly" : R(s.source);
  if (o === "session" && Sn(s.ruleValue) !== l) o = "readonly";
  return {
    behavior: s.ruleBehavior,
    source: s.source,
    rule: l,
    ...a !== null && {
      description: a
    },
    editability: o,
    ...r?.notInEffect && {
      notInEffect: !0
    }
  }
}

